// Bundles scripts/sw/service-worker.js (+ lib/listen, lib/offline modules) into a service worker.
// - `node scripts/build-sw.mjs` (prebuild/predev): public/sw.js with an EMPTY shell, so dev has
//   no fetch handler and HMR is untouched.
// - `node scripts/build-sw.mjs --shell out` (postbuild): out/sw.js with every file of the static
//   export to precache, and a version that changes whenever any of them changes.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

const at = process.argv.indexOf('--shell');
const shellDir = at > 0 ? process.argv[at + 1] : null;
const SKIP = new Set(['sw.js', '.nojekyll']);

function walk(dir, rel = '') {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    const r = rel ? `${rel}/${name}` : name;
    return statSync(full).isDirectory() ? walk(full, r) : SKIP.has(r) ? [] : [r];
  });
}

let files = [];
let version = 'dev';
let outfile = 'public/sw.js';
if (shellDir) {
  files = walk(shellDir).sort();
  const h = createHash('sha256');
  for (const f of files) h.update(f).update('\0').update(readFileSync(path.join(shellDir, f)));
  version = h.digest('hex').slice(0, 12);
  outfile = path.join(shellDir, 'sw.js');
}

await build({
  entryPoints: ['scripts/sw/service-worker.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  outfile,
  define: { __SHELL_FILES__: JSON.stringify(files), __SHELL_VERSION__: JSON.stringify(version) },
  banner: { js: '/* Generated by scripts/build-sw.mjs: do not edit. */' },
});
console.log(`built ${outfile}${shellDir ? ` (shell ${version}: ${files.length} files)` : ''}`);
